function getLocale() {
  return localStorage.getItem('locale') || 'pl';
}

function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? vars[key] : match));
}

function t(key, vars) {
  const locale = getLocale();
  const dict = I18N_DICTS[locale] || I18N_DICTS.pl;
  const str = dict[key] !== undefined ? dict[key] : I18N_DICTS.pl[key];
  if (str === undefined) return key;
  return interpolate(str, vars);
}

function pluralForm(locale, count) {
  const n = Math.abs(count);
  if (locale === 'pl') {
    if (n === 1) return 'one';
    const lastDigit = n % 10;
    const lastTwo = n % 100;
    if (lastDigit >= 2 && lastDigit <= 4 && !(lastTwo >= 12 && lastTwo <= 14)) return 'few';
    return 'many';
  }
  return n === 1 ? 'one' : 'many';
}

function tn(key, count, vars) {
  const locale = getLocale();
  const form = pluralForm(locale, count);
  const fullKey = `${key}.${form}`;
  const dict = I18N_DICTS[locale] || I18N_DICTS.pl;
  let str = dict[fullKey];
  if (str === undefined) str = I18N_DICTS.pl[fullKey];
  if (str === undefined) str = I18N_DICTS.pl[`${key}.many`];
  if (str === undefined) return fullKey;
  return interpolate(str, Object.assign({ count }, vars));
}

function setLocale(locale) {
  localStorage.setItem('locale', locale);
  applyI18n();
  if (typeof onLocaleChange === 'function') onLocaleChange(locale);
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
}

function mountLanguageSwitcher() {
  const select = document.getElementById('langSwitcher');
  if (!select) return;
  const locale = getLocale();
  select.innerHTML = `
    <option value="pl" ${locale === 'pl' ? 'selected' : ''}>PL</option>
    <option value="en" ${locale === 'en' ? 'selected' : ''}>EN</option>
    <option value="de" ${locale === 'de' ? 'selected' : ''}>DE</option>
  `;
  select.addEventListener('change', () => setLocale(select.value));
}

document.addEventListener('DOMContentLoaded', () => {
  applyI18n();
  mountLanguageSwitcher();
});
